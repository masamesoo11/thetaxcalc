#!/usr/bin/env node
/**
 * generate-syndication-content.mjs — fail-safe build-time generator.
 *
 * Reads content/blog/*.json (the site's canonical article store, read at
 * build time by blog-content-loader.ts for SSG) and compiles them into a
 * single JSON map { slug: markdown } at src/generated/syndication-content.json.
 *
 * The syndication API route (/api/syndicate) imports that map to build dev.to
 * payloads. Cloudflare Workers have NO fs at runtime, so the content must be
 * baked into the bundle — this map is ~200KB gzipped for the full library,
 * keeping the worker ~1MB (far under the 3MiB limit).
 *
 * Re-run automatically by the "prebuild" npm lifecycle hook and the build:cf
 * command before every build. The generated file is ALSO committed so a
 * missed regeneration can never break a deploy. This script ALWAYS exits 0
 * (fail-safe): on any error it leaves the committed map in place and just
 * warns.
 *
 * Emits a .ts module (JSON.parse of an escaped string) instead of a raw .json
 * import — resolveJsonModule would make tsc infer 53 giant string-literal
 * types on every build (slow, memory-hungry); a parsed string literal keeps
 * type checking O(1).
 */

import fs from 'fs';
import path from 'path';

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, 'content', 'blog');
const OUT_FILE = path.join(ROOT, 'src', 'generated', 'syndication-content.ts');

try {
  if (!fs.existsSync(SRC_DIR)) {
    console.warn('[syndication-content] content/blog/ not found — keeping committed map.');
    process.exit(0);
  }

  const files = fs.readdirSync(SRC_DIR).filter((f) => f.endsWith('.json'));
  const map = {};
  let count = 0;

  for (const file of files) {
    try {
      const raw = fs.readFileSync(path.join(SRC_DIR, file), 'utf-8');
      const data = JSON.parse(raw);
      if (data && typeof data.slug === 'string' && typeof data.content === 'string' && data.content.trim()) {
        map[data.slug] = data.content;
        count++;
      }
    } catch (err) {
      console.warn(`[syndication-content] skipped ${file}: ${err.message}`);
    }
  }

  const body =
    '/**\n' +
    ' * AUTO-GENERATED by scripts/generate-syndication-content.mjs — DO NOT EDIT.\n' +
    ` * Map of ${count} published post bodies (slug → markdown) compiled from\n` +
    ' * content/blog/*.json at build time, so the syndication API route can\n' +
    ' * build dev.to payloads at runtime (Cloudflare Workers have no fs).\n' +
    ' */\n' +
    `export const SYNDICATION_CONTENT: Record<string, string> = JSON.parse(${JSON.stringify(JSON.stringify(map))});\n`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body);
  console.log(`[syndication-content] wrote ${count} posts (${Math.round(Buffer.byteLength(body) / 1024)}KB) to src/generated/syndication-content.ts`);
} catch (err) {
  console.warn(`[syndication-content] generator failed (non-fatal, committed map remains): ${err.message}`);
}
process.exit(0);
